import { readFile, access } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
import assert from 'node:assert/strict';
const html = (await readFile('index.html', 'utf8')).replace(/\s+/g, ' ');
const sandbox = { window: {} }; runInNewContext(await readFile('assets/js/config.js','utf8'), sandbox);
const config = sandbox.window.BELIAM;
assert.equal(config.contact.whatsapp, '593980271574');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.equal(new Set(ids).size, ids.length, 'IDs duplicados');
for(const match of html.matchAll(/href="#([^"]+)"/g)) assert(ids.includes(match[1]), `Destino inexistente: ${match[1]}`);
const assets = new Set([...html.matchAll(/(?:src|href)="(assets\/[^"]+)"/g)].map(m => m[1]));
for (const entry of config.gallery) assets.add(entry.src);
assets.add(config.beforeAfter.before); assets.add(config.beforeAfter.after);
for (const entry of config.instagramGallery) assets.add(entry.src);
for (const entry of config.testimonials.items) if(entry.avatar) assets.add(entry.avatar);
const css = (await Promise.all(['style.css', 'cosmetic.css', 'sections.css'].map(name => readFile(`assets/css/${name}`, 'utf8')))).join('\n');
for (const match of css.matchAll(/url\('\.\.\/([^']+)'\)/g)) assets.add('assets/' + match[1]);
for (const asset of assets) await access(asset);
assert.equal(config.services.length, 7);
assert.equal(new Set(config.services.map(s => s.id)).size, config.services.length);
assert(!/Amoda|themesflat|lorem ipsum/i.test(html), 'Contenido ajeno a BeLiam');
assert(html.indexOf('id="acerca-de"') > html.indexOf('id="inicio"') && html.indexOf('id="acerca-de"') < html.indexOf('id="servicios"'), 'Acerca de debe ir después del inicio');
for (const section of ['antes-despues', 'opiniones', 'preguntas', 'instagram']) assert(ids.includes(section), `Falta sección: ${section}`);
assert(html.includes('No son reseñas de clientas de BeLiam') && config.testimonials.demo, 'Identificar contenido de muestra');
assert(html.includes('María Vega') && html.includes('Mariuxi Mera'));
assert(html.includes('La imagen del salón es una propuesta de interiorismo') && html.includes('fotografías reales'));
assert(css.includes('prefers-reduced-motion'));
console.log(`Verificación correcta: ${ids.length} destinos únicos, ${assets.size} recursos locales y 7 servicios. WhatsApp configurado para Ecuador.`);
